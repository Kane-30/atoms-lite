export function buildSpecPrompt(userPrompt: string): string {
  return [
    "你是产品经理。把用户的一句话拆成可实现的功能规格。",
    "只输出 JSON。功能项不超过 6 个，页面不超过 3 个。",
    "每个功能必须有稳定的英文 id、中文标题、以及一句可验收描述。",
    "每个功能必须是用户能在界面上点到或直接操作的能力（按钮、表单、列表项等）。",
    "不要把「跨刷新持久化」「样式/脚本分文件」「纯静态约束」单独拆成功能项；这些写进相关功能的验收标准即可。",
    "范围要小，只保留能在一个纯静态网页里做完的事。",
    "需要跨刷新保留的数据，验收里写 window.atomslite.db，并写明集合名，例如 list(\"notes\")。",
    "",
    `用户需求：${userPrompt}`,
  ].join("\n");
}
